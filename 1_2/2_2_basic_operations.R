a <- 1
b <- 0
c <- -1

# sign() return 1:正數, 0:0, -1:負數
sign(a)
sign(b)
sign(c)

# abs() 絕對值

abs(a)
abs(b)
abs(c)

# log
log(10)

log1p(0)      # log(1+0) = log(1) 
log1p(1)      # log(1+1) = log(2) 
log1p(9)      # log(1+9) = log(10)

log(10, 2)    # 以 2 當基底
log2(10)      # log2 代表以 2 當基底
log10(10)     # log10 代表以 10 當基底

# exp

exp(10)
expm1(10)     # expm1(x) = exp(x) - 1
