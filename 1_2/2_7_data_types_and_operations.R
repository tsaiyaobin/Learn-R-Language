# 一、資料型別
x <- 1:5
mode(x)              # 查看型別模式
str(x)               # 查看物件結構
fix(x)               # 開啟編輯器手動修改

x <- as.character(x) # 把數字轉成字串
mode(x)              # "character"
str(x)               # chr [1:5] "1" "2" "3" "4" "5"
fix(x)               # 再次開啟編輯器查看

# 二、邏輯值
x <- (-5) + (0:15)   # x = -5,-4,-3,...,10

x[1] < 0             # 第一個元素是否小於 0
x > 0                # 每個元素是否大於 0
x > 0 & x <= 5       # 每個元素是否同時大於 0 且小於等於 5
x == 3               # 哪些元素等於 3

# 三、特殊值
-3 / 0               # -Inf（無限大）
0 / 0                # NaN（不是數字）
Inf - Inf            # NaN
log(-2)              # NaN（負數沒有對數）
x <- NULL            # 清空內容

# 四、字串
a <- "g"
a

b <- c(1, "x", 2)   # 數字跟字串混在一起，數字會被強制轉成字串
b

x <- paste("Affy", 1:5, sep = "")
# "Affy1" "Affy2" "Affy3" "Affy4" "Affy5"

x <- paste(c("X", "Y"), 1:5, sep = "_")
# "X_1" "Y_2" "X_3" "Y_4" "X_5"

# 五、元素選取
x <- (-5) + (0:15)       # x = -5,-4,-3,...,10

x[1]                     # 第 1 個元素
x[1:3]                   # 第 1 到第 3 個元素
x[-(3:6)]                # 排除第 3 到第 6 個元素
x[x > 0 & x <= 5]        # 選出大於 0 且小於等於 5 的元素
x[!(x > 0 & x <= 5)]     # 排除大於 0 且小於等於 5 的元素

x[1:3] <- 100:102             # 把第 1~3 個元素改成 100, 101, 102
x[(x > 0 & x <= 5)] <- 999    # 把大於 0 且小於等於 5 的元素改成 999