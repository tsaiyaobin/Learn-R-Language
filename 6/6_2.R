# KNN & PCA(續) : 樣本投影結果

## 酵母菌細胞週期資料:第 1 欄 = 基因名稱,第 2~78 欄 = 表達數據,第 79 欄 = 細胞週期高峰階段(peak)
data <- read.table("cycleData_peak.txt", sep = "\t", header = T, as.is = T)
# sep="\t"     以 tab 分隔欄位
# header=T     第一列是欄位名稱
# as.is=T      文字欄位維持字串,不自動轉成 factor

#### 缺失值填補(KNN, K 近鄰法)
BiocManager::install("impute")   # 從 Bioconductor 安裝 impute 套件(只需執行一次)
library(impute)                  # 載入套件


data[, 2:78] <- impute.knn(as.matrix(data[, 2:78])) $ data
# 只對第 2~78 欄(數據部分)做填補
# as.matrix(...) 先轉成矩陣,impute.knn 要求矩陣輸入
# impute.knn 回傳的結果是一個 list,$data 才是填補後的資料矩陣

#### PCA:投影「樣本」
data.prcomp1 <- prcomp(t(data[, 2:78]), scale = T, retx = T)
# t(...)   轉置矩陣 → 讓「樣本」變成列 (以樣本為分析單位)
# scale = T  分析前先把各變數標準化 (平均 0、變異數 1)
# retx = T   回傳投影後的座標 (存在 $x 裡)

summary(data.prcomp1)   # 查看各主成分的變異比例、累積變異
# Standard deviation(標準差):該主成分的標準差,平方後就是它的變異數(特徵值)。
#                            由大到小排,PC1 一定最大——代表它抓到資料中最主要的變異方向。
#-------------------------------------------------------------------------------
# Proportion of Variance(變異比例):這一頁最重要的一列。表示每個主成分解釋了「總變異的百分之幾」。
#                                  例如 PC1 = 0.3820,就是 PC1 一個軸就抓住了整體 38.2% 的變化。
#-------------------------------------------------------------------------------
# Cumulative Proportion(累積比例):從 PC1 累加到當前主成分的總解釋量。這是你決定「要用幾個主成分」的依據。
#                                 看到 PC2 = 0.5445 就代表「前兩個主成分合起來解釋了 54.45% 的變異」。
#-------------------------------------------------------------------------------

str(data.prcomp1)       # 查看物件的內部結構(有哪些欄位可取用)
# $x — 你畫圖真正要用的東西。這是每個樣本投影到各主成分後的新座標。
#-------------------------------------------------------------------------------
# $sdev — 各主成分標準差,summary 的變異比例就是從這裡算出來的(sdev^2 / sum(sdev^2))。
#-------------------------------------------------------------------------------
# $rotation — 載荷(loadings),描述「原始的每個基因」對每個主成分貢獻多大權重。想追問「是哪些基因主導了 PC1」時會用到。
#-------------------------------------------------------------------------------
# $center / $scale — 因為你設了 scale=T,PCA 會先把資料標準化;
#                    這兩個欄位就記錄了「減掉的平均」和「除掉的標準差」,
#                    方便日後還原或套用到新資料。
#-------------------------------------------------------------------------------

## alpha 實驗(第 5~22 欄,共 18 個時間點)##
plot(c(min(data.prcomp1 $ x[, 1]), max(data.prcomp1 $ x[, 1])),
       c(min(data.prcomp1 $ x[, 2]), max(data.prcomp1 $ x[, 2])),
       type = "n", xlab = "1st PC", ylab = "2nd PC")
# 先用兩端點界定 x、y 軸範圍,type="n" 只畫出「空白座標軸」不畫點

text(data.prcomp1 $ x[5:22, 1], data.prcomp1 $ x[5:22, 2], 1:18)
# 在第 1、2 主成分的座標位置,標上編號 1~18(對應 18 個時間點)

## cdc 實驗(第 23~63 欄,共 41 個時間點)##
plot(c(min(data.prcomp1 $ x[,1]), max(data.prcomp1 $ x[, 1])),
       c(min(data.prcomp1 $ x[,2]), max(data.prcomp1 $ x[, 2])),
       type = "n", xlab = "1st PC", ylab = "2nd PC")
text(data.prcomp1 $ x[23:63,1], data.prcomp1 $ x[23:63,2], 1:41)
# 同上,標出 cdc 實驗的 41 個時間點編號
